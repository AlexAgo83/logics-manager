// item_678: aggregate the curated per-release notes into one CHANGELOG.md.
//
// The release notes already exist, one file per version under `changelogs/`, and are
// what the release workflow publishes to GitHub. They were reaching nobody reading the
// npm or PyPI page. This reads those files rather than the GitHub API, so it works
// offline, in CI, and from a source tarball.
//
// `--check` fails when CHANGELOG.md is out of date, which is how the release runbook
// keeps it from going stale one version after it was written.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const repoRoot = process.cwd();
const changelogDir = path.join(repoRoot, "changelogs");
const outputPath = path.join(repoRoot, "CHANGELOG.md");
const checkOnly = process.argv.includes("--check");

// Older lines predate the curated-notes convention and are on GitHub Releases only.
const OLDEST_AGGREGATED = [2, 15, 0];

function versionOf(filename) {
  const match = /^CHANGELOGS_(\d+)_(\d+)_(\d+)\.md$/.exec(filename);
  return match ? match.slice(1, 4).map(Number) : null;
}

function compare(a, b) {
  for (let i = 0; i < 3; i += 1) {
    if (a[i] !== b[i]) return a[i] - b[i];
  }
  return 0;
}

function summarize(body) {
  // The first paragraph after the `# Logics Manager X.Y.Z` title is the release's own
  // one-line summary; the `## ` headings are what changed.
  const lines = body.split("\n");
  const headings = lines
    .filter((line) => line.startsWith("## "))
    .map((line) => line.slice(3).trim())
    .filter((heading) => heading !== "Validation");
  const summaryLines = [];
  for (const line of lines.slice(1)) {
    if (line.startsWith("## ")) break;
    if (line.trim()) summaryLines.push(line.trim());
  }
  return { summary: summaryLines.join(" "), headings };
}

const entries = readdirSync(changelogDir)
  .map((name) => ({ name, version: versionOf(name) }))
  .filter((entry) => entry.version && compare(entry.version, OLDEST_AGGREGATED) >= 0)
  .sort((a, b) => compare(b.version, a.version));

const sections = entries.map(({ name, version }) => {
  const { summary, headings } = summarize(readFileSync(path.join(changelogDir, name), "utf8"));
  const tag = `v${version.join(".")}`;
  return [
    `## ${version.join(".")}`,
    "",
    summary,
    "",
    ...headings.map((heading) => `- ${heading}`),
    "",
    `[Full release note](https://github.com/AlexAgo83/logics-manager/releases/tag/${tag})`,
    "",
  ].join("\n");
});

const rendered = [
  "# Changelog",
  "",
  "What changed in each release of `@grifhinz/logics-manager`. Every entry links its full",
  "note, which carries the reasoning and any migration detail this summary leaves out.",
  "",
  `Releases before ${OLDEST_AGGREGATED.join(".")} are on [GitHub Releases](https://github.com/AlexAgo83/logics-manager/releases) only.`,
  "",
  "Generated by `npm run build:changelog` from `changelogs/`. Do not edit by hand.",
  "",
  ...sections,
].join("\n").replace(/\n{3,}/g, "\n\n");

let current = "";
try {
  current = readFileSync(outputPath, "utf8");
} catch {
  current = "";
}

if (checkOnly) {
  if (current !== rendered) {
    console.error("[changelog] CHANGELOG.md is stale. Run `npm run build:changelog`.");
    process.exit(1);
  }
  console.log(`[changelog] up to date (${entries.length} releases)`);
} else {
  writeFileSync(outputPath, rendered, "utf8");
  console.log(`[changelog] wrote CHANGELOG.md from ${entries.length} curated release note(s)`);
}
